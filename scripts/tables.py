"""Generate paper/tables/*.tex from stats.py.

Same contract as figures.py: computation lives in stats, this file only lays
out. Run `uv run python scripts/tables.py` after the data changes.
"""

import stats

PRIMARY_NAME = {
    "incubation": "AI Agent Incubation",
    "infrastructure": "Infrastructure",
    "financial": "Financial Services",
    "creative": "Creative \\& Virtual",
}
SUBCATEGORY = {
    "builder": "Builder \\& Marketplace",
    "launchpad": "Monetization \\& Launchpad",
    "infrastructure": "Agent Protocol \\& DePIN",
    "trust": "Trust Layer",
    "copilot": "AI-powered Development",
    "defai": "DeFAI Agents",
    "analytics": "Investment Analytics",
    "game": "Game \\& Metaverse",
    "content-creation": "Content Creation",
    "rwa": "AI-powered RWA",
}
REPS = 3

HEAD = r"""%% GENERATED by scripts/tables.py -- DO NOT EDIT BY HAND.
%% Counts are label assignments, so subcategory counts sum to more than the
%% number of classified projects wherever a project carries several labels.
\begin{table*}[ht]
\centering
\caption{Consolidated Web3-AI Agent Taxonomy with Market Metrics\protect\footnotemark}
\label{tab:consolidated_taxonomy}
\resizebox{\textwidth}{!}{%
\begin{tabular}{llcll}
\toprule
\textbf{Primary Category} & \textbf{Avg. MCap (\$M)} & \textbf{Subcategory} & \textbf{Count} & \textbf{Representative Projects} \\
\midrule"""

TAIL = r"""\bottomrule
\end{tabular}%
}
\end{table*}"""


def escape(s):
    for bad, good in (("\u2014", "---"), ("\u2013", "--"), ("\u2019", "'")):
        s = s.replace(bad, good)
    return s.replace("&", "\\&").replace("_", "\\_").replace("%", "\\%")


def reps(rows, label):
    """Largest projects carrying ``label``, preferring ones that carry it alone.

    A multi-label project would otherwise represent two subcategories at once,
    which reads as an error even though it is not.
    """
    hit = [r for r in rows if label in r["labels"]]
    hit.sort(key=lambda r: (len(r["labels"]) > 1, -stats.mcap(r)))
    return ", ".join(escape(r["name"]) for r in hit[:REPS])


def main():
    rows = stats.cls()
    prim, sub = stats.by_primary(rows), stats.by_subcategory(rows)
    subs_of = {p: [s for s in stats.SUBCAT_ORDER if stats.PRIMARY[s] == p]
               for p in stats.PRIMARY_ORDER}

    lines = [HEAD]
    for i, p in enumerate(stats.PRIMARY_ORDER):
        members = [s for s in subs_of[p] if s in sub]
        span = len(members)
        head = (f"\\multirow{{{span}}}{{*}}{{{PRIMARY_NAME[p]} ({prim[p]['n']})}} & "
                f"\\multirow{{{span}}}{{*}}{{{prim[p]['mean'] / 1e6:.1f}}}")
        if i:
            lines.append("\\cline{1-5}")
        for j, s in enumerate(members):
            if j:
                lines.append("\\cline{3-5}")
            left = head if j == 0 else " & "
            lines.append(f"{left} & {SUBCATEGORY[s]} & {sub[s]['n']} & "
                         f"{reps(rows, s)} \\\\")
    lines.append(TAIL)

    out = stats.ROOT.parent / "paper/tables/taxonomy.tex"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
