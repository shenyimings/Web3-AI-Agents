r"""Generate paper/numbers.tex -- every number the manuscript states, as a macro.

    uv run python scripts/macros.py

The manuscript must not contain a typed-in figure. Each number here is computed
by ``stats.py`` and formatted once, so a re-collection changes the paper by
regenerating this file rather than by a hand sweep, and a figure cannot drift
from the sentence beside it.

*Macro names carry their frame.* ``\nPop...`` is the screened T2 population,
``\nCls...`` a classified-project attribute, ``\nCoh...`` the archived T1
cohort, ``\nPan...`` the 133 T1 projects from date-restricted search, ``\nRep...`` the
token-frame/repo-frame comparison. Mixing frames inside one subsection is the
error this naming exists to make visible: a ``\nPop`` macro in a per-project
paragraph is wrong on sight.

*Formatting lives here, not in the prose.* Thousands separators, the
billion/million cut, percent escaping and ``\xspace`` are decided once below.
"""

