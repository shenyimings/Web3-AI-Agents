# --- formatting --------------------------------------------------------------

def num(x):
    """An integer with a LaTeX-safe thousands separator."""
    return f"{round(x):,}".replace(",", "{,}")


def usd(x):
    """Money as the paper writes it: billions and millions in words."""
    if x >= 1e9:
        return f"\\${x/1e9:.2f} billion"
    if x >= 1e6:
        return f"\\${x/1e6:.1f} million" if x < 1e8 else f"\\${x/1e6:.0f} million"
    if x >= 1e3:
        return f"\\${num(x)}"
    return f"\\${x:.0f}"


def pct(x, digits=1):
    """A share given as a fraction, rendered as a percentage."""
    return f"{100*x:.{digits}f}\\%"


CHAIN_NAME = {"bnb": "BNB Chain", "base": "Base", "ethereum": "Ethereum mainnet",
              "celo": "Celo", "monad": "Monad", "avalanche_c": "Avalanche",
              "gnosis": "Gnosis", "megaeth": "MegaETH"}


def month_name(iso):
    """A YYYY-MM as the paper writes it: "December 2025"."""
    y, mo = iso.split("-")
    return f"{datetime.date(int(y), int(mo), 1):%B} {y}"


def dec(x, digits=3):
    return f"{x:.{digits}f}"


def times(x):
    return f"{x:.2f}$\\times$"


def date(iso):
    d = datetime.date.fromisoformat(iso)
    return f"{d.day} {d:%B} {d.year}"


def word(n):
    names = ["zero", "one", "two", "three", "four", "five", "six", "seven",
             "eight", "nine", "ten", "eleven", "twelve", "thirteen", "fourteen",
             "fifteen", "sixteen", "seventeen", "eighteen", "nineteen", "twenty"]
    return names[n] if n < len(names) else num(n)


class Macros:
    """Collects ``name -> (rendered, raw)`` pairs under frame headings."""

    def __init__(self):
        self.blocks = []

    def block(self, frame, note):
        self.blocks.append((frame, note, []))
        return self

    def add(self, name, rendered, raw=None):
        self.blocks[-1][2].append((name, rendered, raw))
        return self

    def group(self, prefix, bucket, *, share_of=None, mean=True):
        """The standard count/value/mean/share quartet for one aggregate."""
        self.add(prefix + "Count", num(bucket["n"]), bucket["n"])
        self.add(prefix + "Mcap", usd(bucket["mcap"]), bucket["mcap"])
        if mean:
            self.add(prefix + "Mean", usd(bucket["mean"]), bucket["mean"])
        if share_of:
            self.add(prefix + "Share", pct(bucket["mcap"] / share_of),
                     bucket["mcap"] / share_of)
        return self

    def render(self):
        lines = [
            "% numbers.tex -- GENERATED by bcra-artifact/scripts/macros.py.",
            "% DO NOT EDIT. Change the data, then regenerate:",
            "%     cd bcra-artifact && uv run python scripts/macros.py",
            "%",
            "% Macro names carry their population frame (nPop/nCls/nCoh/nPan/nRep).",
            "% Do not mix frames within a subsection; see scripts/macros.py.",
            f"% Generated {datetime.date.today().isoformat()}.",
            "",
        ]
        for frame, note, items in self.blocks:
            width = max(len(n) for n, _, _ in items) + 2
            lines += [f"% --- {frame} " + "-" * max(0, 68 - len(frame)),
                      *[f"% {l}" for l in note.strip().splitlines()], ""]
            for name, rendered, _ in items:
                cmd = f"\\newcommand{{\\{name}}}"
                lines.append(f"{cmd:<{width+15}}{{{rendered}\\xspace}}")
            lines.append("")
        return "\n".join(lines)

    def as_json(self):
        return {name: {"tex": rendered, "value": raw}
                for _, _, items in self.blocks for name, rendered, raw in items}


# --- the numbers -------------------------------------------------------------

def build():
    m = Macros()
    pop, scr = s.pop(), s.screening()
    cls = s.cls()
    total = sum(s.mcap(r) for r in cls)
    coh, pan, rep = s.coh(), s.panel(), s.rep()

    # ---- study design
    t1, t2 = coh["t1_date"], coh["t2_date"]
    months = ((datetime.date.fromisoformat(t2).year
               - datetime.date.fromisoformat(t1).year) * 12
              + datetime.date.fromisoformat(t2).month
              - datetime.date.fromisoformat(t1).month)
    m.block("study design", "The two timepoints and the window between them.")
    m.add("nDateOne", date(t1), t1)
    m.add("nDateTwo", date(t2), t2)
    m.add("nWindow", f"{word(months)} months", months)
    m.add("nAliveFloor", f"\\${s.ALIVE_USD/1e6:.0f} million", s.ALIVE_USD)
    m.add("nStaleDays", num(s.STALE_DAYS), s.STALE_DAYS)

    # ---- Pop: the screened T2 population
    m.block("nPop -- screened T2 population", f"""
{pop['n']} tokens, {t2}. Aggregate and concentration results ONLY:
this frame has no per-project attributes. Screening: coding/SCREENING-CRITERIA.md.
""")
    m.group("nPop", {"n": pop["n"], "mcap": pop["mcap"], "mean": pop["mean"]},
            mean=True)
    m.add("nPopMedian", usd(pop["median"]), pop["median"])
    m.add("nPopGini", dec(pop["gini"]), pop["gini"])
    for frac, label in [(0.01, "Pct"), (0.05, "Twentieth"), (0.10, "Decile")]:
        share, k = s.top_share(pop["values"], frac)
        m.add(f"nPopTop{label}Count", num(k), k)
        m.add(f"nPopTop{label}Share", pct(share), share)
    share, _ = s.top_share(pop["values"], 0.10)
    m.add("nPopBottomShare", pct(1 - share), 1 - share)
    bands = s.tiers(pop["values"], [1e5, 1e6, 1e7, 1e8])
    for (lo, hi, n, _), label in zip(bands, ["SubHundredK", "HundredKToM",
                                             "MToTenM", "TenMToHundredM",
                                             "AboveHundredM"]):
        m.add(f"nPop{label}Count", num(n), n)
        m.add(f"nPop{label}Share", pct(n / pop["n"]), n / pop["n"])

    # ---- screening funnel
    m.block("nScr -- the screening funnel", """
Methodology only. Each rule's removal count and the value it carries.
""")
    m.add("nScrFrame", num(scr["frame"]), scr["frame"])
    m.add("nScrCapitalised", num(scr["capitalised"]), scr["capitalised"])
    m.add("nScrNotCapitalised", num(scr["not_capitalised"]), scr["not_capitalised"])
    m.add("nScrDerivative", num(scr["s2a"]), scr["s2a"])
    m.add("nScrDerivativeValue", usd(scr["s2a_value"]), scr["s2a_value"])
    m.add("nScrDuplicate", num(scr["s2b"]), scr["s2b"])
    m.add("nScrDuplicateGroups", num(scr["s2b_groups"]), scr["s2b_groups"])
    m.add("nScrMeme", num(scr["s5"]), scr["s5"])
    m.add("nScrMemeValue", usd(scr["s5_value"]), scr["s5_value"])
    m.add("nScrMechanical", num(scr["mechanical"]), scr["mechanical"])
    m.add("nScrMechanicalMcap", usd(scr["mechanical_mcap"]), scr["mechanical_mcap"])
    m.add("nScrNoDescription", num(scr["no_description"]), scr["no_description"])
    m.add("nScrNoDescriptionValue", usd(scr["no_description_value"]),
          scr["no_description_value"])
    m.add("nScrNoDescriptionShare", pct(scr["no_description_value"] / scr["mechanical_mcap"]),
          scr["no_description_value"] / scr["mechanical_mcap"])

    # ---- Cls: the classified projects
    residual, coding = s.residual(), s.coding(cls)
    m.block("nCls -- classified projects", f"""
{len(cls)} projects carrying at least one subcategory label. EVERY per-project
attribute lives in this frame: taxonomy, facet, chain, valuation.
""")
    m.group("nCls", {"n": len(cls), "mcap": total, "mean": total / len(cls)})
    m.add("nClsOutOfScope", num(residual["out-of-scope"]), residual["out-of-scope"])
    m.add("nClsUnclassifiable", num(residual["unclassifiable"]), residual["unclassifiable"])
    m.add("nClsRule", num(coding["provenance"]["rule"]), coding["provenance"]["rule"])
    m.add("nClsRead", num(coding["provenance"]["read"]), coding["provenance"]["read"])
    for level in ["high", "medium", "low"]:
        n = coding["confidence"][level]
        m.add(f"nClsConf{level.title()}", num(n), n)
    m.add("nClsMulti", num(coding["multi_label"]), coding["multi_label"])
    m.add("nClsMultiShare", pct(coding["multi_label"] / len(cls)),
          coding["multi_label"] / len(cls))
    m.add("nClsMultiMcap", usd(coding["multi_label_mcap"]), coding["multi_label_mcap"])
    m.add("nClsMultiMcapShare", pct(coding["multi_label_mcap"] / total),
          coding["multi_label_mcap"] / total)

    primary = s.by_primary(cls)
    names = {"incubation": "Incub", "infrastructure": "Infra",
             "financial": "Fin", "creative": "Creative"}
    m.block("nCls -- primary categories", """
Categories overlap: a project with two labels counts in each, so counts sum to
assignments, not to nClsCount. Shares are of nClsMcap.
""")
    for key in s.PRIMARY_ORDER:
        m.group("nCls" + names[key], primary[key], share_of=total)
    # Share of assignments, not of projects: the denominator is the sum over
    # categories, which is the only base a T1/T2 composition comparison can use.
    cls_assign = sum(primary[k]["n"] for k in s.PRIMARY_ORDER)
    m.add("nClsFinCountShare", pct(primary["financial"]["n"] / cls_assign),
          primary["financial"]["n"] / cls_assign)

    subs = s.by_subcategory(cls)
    subnames = {"builder": "Builder", "launchpad": "Launchpad",
                "infrastructure": "Protocol", "trust": "Trust",
                "copilot": "Copilot", "defai": "DeFAI", "analytics": "Analytics",
                "game": "Game", "content-creation": "Content", "rwa": "RWA"}
    m.block("nCls -- subcategories", "Same overlap rule as the primary categories.")
    for key in s.SUBCAT_ORDER:
        m.group("nCls" + subnames[key], subs[key], share_of=total)

    facets = s.by_facet(cls)
    m.block("nCls -- infrastructure facets", """
A strict refinement of the infrastructure subcategory, T2 only. The four
facets partition it exactly; dropping them reproduces the T1-comparable coding.
""")
    for key in s.FACET_ORDER:
        m.group("nClsFacet" + key.title(), facets[key],
                share_of=subs["infrastructure"]["mcap"])

    chains = s.by_platform(cls)
    deployments = sum(c["n"] for c in chains.values())
    chainnames = {"base": "Base", "ethereum": "Ethereum", "solana": "Solana",
                  "binance-smart-chain": "BNB", "bittensor": "Bittensor",
                  "robinhood": "Robinhood", "arbitrum-one": "Arbitrum",
                  "polygon-pos": "Polygon"}
    m.block("nCls -- blockchains", """
One entry per deployment: a multi-chain project counts on each chain, so these
sum to nClsDeployments rather than to nClsCount. Tokens CoinGecko lists with no
platform are native coins of their own chain and are not counted.
""")
    ch = s.chains(cls)
    m.add("nClsChains", num(ch["networks"]), ch["networks"])
    m.add("nClsDeployments", num(ch["deployments"]), ch["deployments"])
    m.add("nClsListed", num(ch["listed"]), ch["listed"])
    m.add("nClsListedShare", pct(ch["listed"] / len(cls)), ch["listed"] / len(cls))
    m.add("nClsMultichain", num(ch["multichain"]), ch["multichain"])
    m.add("nClsMultichainShare", pct(ch["multichain"] / ch["listed"]),
          ch["multichain"] / ch["listed"])
    for key, label in chainnames.items():
        bucket = chains.get(key)
        if bucket:
            m.group("nClsChain" + label, bucket, share_of=total)
            m.add(f"nClsChain{label}CountShare", pct(bucket["n"] / deployments),
                  bucket["n"] / deployments)

    subname = {"builder": "Builder", "launchpad": "Launchpad",
               "infrastructure": "Protocol", "trust": "Trust",
               "copilot": "Copilot", "defai": "DeFAI", "analytics": "Analytics",
               "game": "Game", "content-creation": "Content", "rwa": "RWA"}
    m.block("nCls -- co-occurrence and repository activity", """
Pair counts are over the multi-label projects; activity rates are over the
classified projects that publish a repository at all, so they compare
categories rather than estimating an absolute level.
""")
    for rank, ((a, b), n) in enumerate(s.pairs(cls), 1):
        m.add(f"nClsPair{word(rank).title()}", num(n), n)
        m.add(f"nClsPair{word(rank).title()}Name",
              f"\\textit{{{subname[a]}}} with \\textit{{{subname[b]}}}", f"{a}+{b}")
    act = s.repo_activity(cls)
    m.add("nActCount", num(act["_projects"]), act["_projects"])
    for key in s.PRIMARY_ORDER:
        m.add("nAct" + names[key] + "Count", num(act[key]["n"]), act[key]["n"])
        m.add("nAct" + names[key] + "Rate", pct(act[key]["rate"], 0), act[key]["rate"])

    tr = s.trend()
    m.block("nTrend -- the monthly series behind the trend figure", """
Generated so the figure's caption cannot drift from the figure. The window is
the 365 days the CoinGecko API returns, truncated at the cutoff.
""")
    m.add("nTrendTracked", num(tr["tracked"]), tr["tracked"])
    m.add("nTrendSpan", f"{word(tr['span'])} months", tr["span"])
    m.add("nTrendFirst", tr["first"], tr["first"])
    m.add("nTrendLast", tr["last"], tr["last"])
    m.add("nTrendLiveOne", num(tr["live_first"]), tr["live_first"])
    m.add("nTrendLiveTwo", num(tr["live_last"]), tr["live_last"])
    m.add("nTrendMcapOne", usd(tr["value_first"]), tr["value_first"])
    m.add("nTrendMcapTwo", usd(tr["value_last"]), tr["value_last"])

    # ---- Coh: the archived T1 cohort
    m.block("nCoh -- T1 cohort fixed from web archives", """
Membership fixed at T1 from archived CoinGecko category pages; value read per
coin at each date. Survival and value change ONLY.
""")
    m.add("nCohCount", num(coh["n_t1"]), coh["n_t1"])
    m.add("nCohSurvived", num(coh["n_survived"]), coh["n_survived"])
    m.add("nCohSurvival", pct(coh["survival"]), coh["survival"])
    m.add("nCohExit", num(coh["n_t1"] - coh["n_survived"]), coh["n_t1"] - coh["n_survived"])
    m.add("nCohMcapOne", usd(coh["t1_cohort_usd"]), coh["t1_cohort_usd"])
    m.add("nCohMcapTwo", usd(coh["t2_cohort_usd"]), coh["t2_cohort_usd"])
    m.add("nCohChange", pct(abs(coh["cohort_value_change"])), coh["cohort_value_change"])
    m.add("nCohSurvivorChange", pct(abs(coh["survivor_value_change"])),
          coh["survivor_value_change"])
    m.add("nCohExitValue", usd(coh["value_lost_to_exits"]), coh["value_lost_to_exits"])
    m.add("nCohGiniOne", dec(coh["gini_t1_full_cohort"]), coh["gini_t1_full_cohort"])
    m.add("nCohGiniTwo", dec(coh["gini_t2"]), coh["gini_t2"])
    m.add("nCohTopDecileOne", pct(coh["top_decile_t1"]), coh["top_decile_t1"])
    m.add("nCohTopDecileTwo", pct(coh["top_decile_t2"]), coh["top_decile_t2"])
    m.add("nCohBottomShare", pct(1 - coh["top_decile_t1"]), 1 - coh["top_decile_t1"])
    m.add("nCohMedianOne", usd(sorted(coh["values"])[len(coh["values"]) // 2]),
          sorted(coh["values"])[len(coh["values"]) // 2])

    # ---- Pan: the T1 search set
    m.block("nPan -- the 133 T1 projects from date-restricted search", """
Found through Google search restricted to pages dated before T1, traced forward.
RQ1 case study and the T1 composition comparison ONLY.
""")
    m.add("nPanCount", num(pan["n"]), pan["n"])
    m.add("nPanCapitalised", num(pan["capitalised_t1"]), pan["capitalised_t1"])
    m.add("nPanMcapOne", usd(pan["t1_mcap"]), pan["t1_mcap"])
    m.add("nPanMatched", num(pan["matched"]), pan["matched"])
    m.add("nPanMcapTwo", usd(pan["t2_mcap"]), pan["t2_mcap"])
    m.add("nPanRetention", pct(pan["matched"] / pan["capitalised_t1"]),
          pan["matched"] / pan["capitalised_t1"])
    cap = pan["capitalised_t1"]
    for key, prefix in [("in category", "nPanKept"),
                        ("traded, left category", "nPanLeft"),
                        ("no token", "nPanGone")]:
        n = pan["status"].get(key, 0)
        m.add(prefix, num(n), n)
        m.add(prefix + "Share", pct(n / cap, 0), n / cap)
    m.add("nPanStillTradedShare",
          pct((cap - pan["status"].get("no token", 0)) / cap, 0),
          (cap - pan["status"].get("no token", 0)) / cap)
    m.add("nPanListed", num(pan["listed"]), pan["listed"])
    m.add("nPanKeptUncapitalised", word(pan["kept_uncapitalised"]),
          pan["kept_uncapitalised"])
    m.add("nPanKeptMcapOne", usd(pan["kept_t1"]), pan["kept_t1"])
    m.add("nPanKeptMcapTwo", usd(pan["kept_t2"]), pan["kept_t2"])
    m.add("nPanKeptRetained", pct(pan["kept_t2"] / pan["kept_t1"], 0),
          pan["kept_t2"] / pan["kept_t1"])
    m.add("nPanKeptMedian", pct(pan["kept_median"]), pan["kept_median"])
    m.add("nPanGrew", word(pan["grew"]), pan["grew"])
    m.add("nPanLostNinety", word(pan["lost_ninety"]), pan["lost_ninety"])
    m.add("nPanLostNinetyNine", word(pan["lost_ninetynine"]), pan["lost_ninetynine"])
    # A project name that already carries capitalization is the project's own
    # spelling; only an all-lowercase listing key needs titling.
    cased = lambda n: n if n.lower() != n else n.title()
    m.add("nPanKeptPriced", num(pan["kept"]), pan["kept"])
    for rank, row in enumerate(pan["top"], 1):
        r = row["t2"] / row["t1"]
        m.add(f"nPanTop{word(rank).title()}Name", cased(row["project"]), row["project"])
        m.add(f"nPanTop{word(rank).title()}", times(r), r)
    for rank, row in enumerate(pan["holdings"], 1):
        m.add(f"nPanHolding{word(rank).title()}Name", cased(row["project"]),
              row["project"])
        m.add(f"nPanHolding{word(rank).title()}Retained",
              times(row["t2"] / row["t1"]), row["t2"] / row["t1"])
    m.add("nPanHoldingsShare", pct(pan["holdings_share"]), pan["holdings_share"])
    m.add("nPanExOutlier", pct(pan["ex_holdings"], 0), pan["ex_holdings"])
    t1 = s.t1_labels()
    t1_total = sum(s.mcap(r) for r in t1)
    m.add("nPanCoded", num(len(t1)), len(t1))
    m.add("nPanCodedMcap", usd(t1_total), t1_total)
    t1_primary = s.by_primary(t1)
    for key in s.PRIMARY_ORDER:
        m.group("nPan" + names[key], t1_primary[key], share_of=t1_total)
    t1_assign = sum(t1_primary[k]["n"] for k in s.PRIMARY_ORDER)
    m.add("nPanFinCountShare", pct(t1_primary["financial"]["n"] / t1_assign),
          t1_primary["financial"]["n"] / t1_assign)
    sub = s.panel_by_subcategory()
    for key, label in [("trust", "Trust"), ("launchpad", "Launchpad"),
                       ("defai", "DeFAI"), ("content-creation", "Content"),
                       ("infrastructure", "Protocol"), ("game", "Game")]:
        m.add(f"nPanMedian{label}", pct(sub[key]["median"], 0), sub[key]["median"])
        m.add(f"nPanAlive{label}", pct(sub[key]["alive_share"], 0), sub[key]["alive_share"])

    # ---- Rep: token frame vs repo frame
    m.block("nRep -- token frame vs repo frame", """
The coverage comparison. This frame answers what a market-capitalization frame
cannot see, and appears in that subsection ONLY.
""")
    m.add("nRepCount", num(rep["n"]), rep["n"])
    m.add("nRepToken", num(rep["token"]), rep["token"])
    m.add("nRepRepo", num(rep["repo"]), rep["repo"])
    m.add("nRepBoth", num(rep["both"]), rep["both"])
    m.add("nRepTokenOnly", num(rep["token_only"]), rep["token_only"])
    m.add("nRepRepoOnly", num(rep["repo_only"]), rep["repo_only"])
    m.add("nRepActive", num(rep["repo_active"]), rep["repo_active"])
    m.add("nRepAlive", num(rep["token_alive"]), rep["token_alive"])
    active_repo_only = sum(1 for r in rep["rows"]
                           if r["has_repo"] and not r["has_token"] and r["repo_active"])
    m.add("nRepRepoOnlyActive", num(active_repo_only), active_repo_only)
    live = s.liveness()
    m.add("nRepLiveBoth", num(live["both"]), live["both"])
    m.add("nRepLiveNeither", num(live["neither"]), live["neither"])
    m.add("nRepLiveCodeOnly", num(live["code_only"]), live["code_only"])
    m.add("nRepLiveTokenOnly", num(live["token_only"]), live["token_only"])
    m.add("nRepLiveShare", pct(live["both_share"], 0), live["both_share"])
    g = s.gh()
    m.add("nRepPool", num(g["pool"]), g["pool"])
    m.add("nRepGroups", num(g["groups"]), g["groups"])
    m.add("nRepKwLegacy", num(g["legacy"]), g["legacy"])
    m.add("nRepKwStandards", num(g["standards"]), g["standards"])
    m.add("nRepKwBoth", word(g["both"]), g["both"])
    m.add("nRepSingleShare", pct(g["single_share"], 0), g["single_share"])
    m.add("nRepLargestGroup", word(g["largest"]), g["largest"])

    # ---- the standards layer
    gov, x402, erc = s.governance(), s.x402(), s.erc8004()
    m.block("nGov / nX402 / nErc -- governance and the standards layer", """
nGov is a subset of nCls. nX402 and nErc are on-chain measurements, independent
of every token frame above.
""")
    m.add("nGovDescribed", num(gov["with_description"]), gov["with_description"])
    m.add("nGovVocabulary", num(gov["governance_vocabulary"]), gov["governance_vocabulary"])
    m.add("nGovWithAgent", num(gov["governance_with_agent"]), gov["governance_with_agent"])
    for key, prefix in [("token_utility", "nGovUtility"),
                        ("agent_as_actor", "nGovActor"),
                        ("agent_as_subject", "nGovSubject")]:
        m.add(prefix + "Count", num(gov[key]["n"]), gov[key]["n"])
        m.add(prefix + "Mcap", usd(gov[key]["mcap_usd"]), gov[key]["mcap_usd"])
        m.add(prefix + "Share", pct(gov[key]["share"], 1), gov[key]["share"])
